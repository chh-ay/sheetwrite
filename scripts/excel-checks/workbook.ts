function create_grid(
  sheetwrite: Sheetwrite,
  snapshot: WorkbookSnapshot,
): { grid: Grid; dispose(): void } {
  const host = document.createElement("div");
  document.body.appendChild(host);
  const grid = sheetwrite.core.createGridFromSnapshot(host, snapshot);
  return {
    grid,
    dispose() {
      grid.destroy();
      host.remove();
    },
  };
}

/**
 * Read each "Excel shows" cell in Sheetwrite: that text is Sheetwrite's
 * answer. Checks without steps are read first, so another check's steps (13
 * edits the orders that 12's pivot reads) do not change them; Excel keeps
 * those pivots as plain values.
 */
async function sheetwrite_answers(
  sheetwrite: Sheetwrite,
  built: Layout,
  start: CheckSheet,
): Promise<void> {
  const scratch = create_grid(sheetwrite, workbook_snapshot(built, start));
  const read_answers = (checks: readonly BuiltCheck[]) => {
    for (const { sheet } of checks) {
      const block = sheet?.result;
      if (!sheet || !block) continue;
      for (let index = 0; index < block.count; index++) {
        const row = block.row + 1 + index;
        const answer = scratch.grid.getCellText({
          sheet: sheet.id,
          row,
          col: block.col + EXCEL_OFFSET,
        });
        sheet.put(row, block.col + SHEETWRITE_OFFSET, answer);
      }
    }
  };
  try {
    read_answers(built.checks.filter((check) => !check.steps));
    for (const check of built.checks) await check.steps?.(scratch.grid);
    read_answers(built.checks.filter((check) => check.steps));
  } finally {
    scratch.dispose();
  }
}

/** The export's warnings, and the bytes of the workbook. */
export interface ExcelChecksWorkbook {
  readonly bytes: Uint8Array;
  readonly warnings: readonly string[];
  readonly checks: readonly CheckInfo[];
  /** Results blocks by sheet name. */
  readonly results: ReadonlyMap<string, ResultBlock>;
}

/**
 * Build the workbook. With `afterSteps`, check 15's rename is already made,
 * so the script can compare the charts Excel saves with the charts Sheetwrite
 * writes for the same cells. Check 13's edit stays out: the pivots of checks
 * 12 and 14 are plain values in Excel and do not follow it.
 */
export async function excelChecksWorkbook(
  sheetwrite: Sheetwrite,
  options: { afterSteps?: boolean } = {},
): Promise<ExcelChecksWorkbook> {
  const built = await layout(sheetwrite, options.afterSteps === true);
  const start = start_sheet(built.checks);
  await sheetwrite_answers(sheetwrite, built, start);
  const final = create_grid(sheetwrite, workbook_snapshot(built, start));
  try {
    const warnings: string[] = [];
    const bytes = await sheetwrite.core.toXlsxWorkbook(final.grid, {
      powerQuery: sheetwrite.powerQuery,
      onWarning: (warning) => warnings.push(warning.message),
    });
    const results = new Map<string, ResultBlock>();
    for (const { sheet } of built.checks) if (sheet?.result) results.set(sheet.name, sheet.result);
    return { bytes, warnings, checks: built.checks.map((check) => check.info), results };
  } finally {
    final.dispose();
  }
}
