/** Check 1: the sort-order cases, stacked by case, sorted with two levels at once. */
async function sort_order_check(sheetwrite: Sheetwrite): Promise<BuiltCheck> {
  const sheet = new CheckSheet("c01", "1 Sort order");
  const fixture = await sheetwrite.core.fromXlsxWorkbook(
    readFileSync(resolve(ROOT, "packages/xlsx/test/fixtures/excel-sort-order-input.xlsx")),
  );
  const ascending = fixture.sheets.find((candidate) => candidate.name === "Ascending");
  if (!ascending) throw new Error("excel-sort-order-input.xlsx has no Ascending sheet");
  const cases = new Map<number, Map<number, SnapshotCell["value"]>>();
  for (const block of ascending.cells) {
    for (const cell of block.cells) {
      const col = block.startCol + cell.colOffset;
      const column = cases.get(col) ?? new Map<number, SnapshotCell["value"]>();
      column.set(block.startRow + cell.rowOffset, cell.value);
      cases.set(col, column);
    }
  }
  const stacked: Input[][] = [];
  for (const [col, column] of [...cases].sort(([left], [right]) => left - right)) {
    const length = Math.max(...column.keys()) + 1;
    for (let place = 0; place < length; place++) {
      const value = column.get(place);
      const input =
        value?.kind === "formula"
          ? formula(value.src)
          : value?.kind === "literal"
            ? value.value
            : null;
      stacked.push([col + 1, input, place + 1]);
    }
  }
  const last = INPUT_ROW + stacked.length;
  const header = ["Case", "Value", "Place"];
  sheet.grid(INPUT_ROW, 0, [header, ...stacked]);
  sheet.grid(INPUT_ROW, 4, [header, ...stacked]);
  const rows: ResultRow[] = [];
  for (const [block, col] of [
    ["A to Z", 1],
    ["Z to A", 5],
  ] as const) {
    stacked.forEach((_, index) => {
      const row = INPUT_ROW + 1 + index;
      rows.push({ what: `${block}, ${a1(row, col)}`, excel: content(a1(row, col)) });
    });
  }
  sheet.results(INPUT_ROW, 8, rows);
  sheet.intro(
    "Check 1 (#353): Excel's sort order",
    "Each case of packages/wasm/src/sort_order_tests.rs is one Case number. Sorting by Case, then Value, sorts each case on its own.",
    [
      `Select A9:C${last + 1}. Select Data › Sort. Keep "My data has headers" checked.`,
      "Sort by Case, Smallest to Largest. Select Add Level: then by Value, A to Z (or Smallest to Largest). Select OK.",
      `Select E9:G${last + 1}, Data › Sort: by Case, Smallest to Largest, then by Value, Z to A (or Largest to Smallest). OK.`,
    ],
  );
  return {
    info: { sheet: sheet.name, check: "1. Sort order", issues: "#353", seconds: 60 },
    sheet,
    steps: (grid) => {
      grid.sortRange(
        range(sheet.id, INPUT_ROW, 0, last, 2),
        [
          { col: 0, ascending: true },
          { col: 1, ascending: true },
        ],
        { hasHeader: true },
      );
      grid.sortRange(
        range(sheet.id, INPUT_ROW, 4, last, 6),
        [
          { col: 4, ascending: true },
          { col: 5, ascending: false },
        ],
        { hasHeader: true },
      );
    },
  };
}

