/** 2026-01-03, a Saturday, as an Excel date serial. */
const SATURDAY_SERIAL = 46025;

interface FillCase {
  readonly col: number;
  readonly source: readonly (string | number)[];
  readonly length: number;
  readonly options?: FillOptions;
}

/** Check 18: AutoFill series that Excel's AutoFill table does not list. */
function auto_fill_check(): BuiltCheck {
  const sheet = new CheckSheet("c18", "18 AutoFill");
  const cases: FillCase[] = [
    { col: 0, source: ["A1", "B1"], length: 6 },
    { col: 2, source: ["Quarter 4"], length: 5 },
    { col: 3, source: ["1 Apple"], length: 5 },
    { col: 4, source: ["Q4 2024"], length: 5 },
    { col: 6, source: [SATURDAY_SERIAL], length: 6, options: { unit: "weekday" } },
  ];
  const filled: { row: number; col: number; value: string | number }[] = [];
  const rows: ResultRow[] = [];
  for (const fill of cases) {
    const is_date = fill.options?.unit === "weekday";
    fill.source.forEach((value, index) =>
      sheet.put(
        INPUT_ROW + index,
        fill.col,
        value,
        is_date ? { numberFormat: DATE_FORMAT } : undefined,
      ),
    );
    const plan = detectFillSeries(
      fill.source.map((value) => ({
        value,
        isFormula: false,
        ...(is_date ? { isDate: is_date } : {}),
      })),
      fill.options,
    );
    for (let place = fill.source.length; place < fill.length; place++) {
      const ref = a1(INPUT_ROW + place, fill.col);
      rows.push({ what: ref, excel: is_date ? date_content(ref) : content(ref) });
      const step = plan.stepAt(place);
      const value = step.kind === "value" ? step.value : fill.source[step.sourceIndex];
      if (typeof value !== "string" && typeof value !== "number") {
        throw new Error(`AutoFill of ${ref} planned a ${typeof value}`);
      }
      filled.push({ row: INPUT_ROW + place, col: fill.col, value });
    }
  }
  sheet.results(INPUT_ROW, 8, rows);
  sheet.intro(
    "Check 18 (#827, #824): AutoFill series that Excel's table does not list",
    "Drag each fill handle down with the mouse; Sheetwrite generalises Qtr3, 1st Period and text1, textA.",
    [
      "Select A9:A10 and drag the fill handle down to A14.",
      "Drag the fill handle of C9 down to C13.",
      "Drag the fill handle of D9 down to D13, then of E9 down to E13.",
      "Drag the fill handle of G9 down to G14. Select Auto Fill Options › Fill Weekdays.",
    ],
  );
  return {
    info: {
      sheet: sheet.name,
      check: "18. AutoFill series beyond Excel's table",
      issues: "#827, #824",
      seconds: 60,
    },
    sheet,
    // The fill handle has no API; its series planner gives the values a drag writes.
    steps: (grid) => {
      grid.applyTransaction({
        patches: filled.map(({ row, col, value }) => ({
          op: "set" as const,
          addr: { sheet: sheet.id, row, col },
          value: { kind: "literal" as const, value },
        })),
      });
    },
  };
}

